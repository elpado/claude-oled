const glyphW, glyphH, advance = 5, 7, 6

func glyph(r rune) [7]string {
	if g, ok := glyphs[unicode.ToUpper(r)]; ok {
		return g
	}
	return glyphs['?']
}

func textWidth(s string) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*advance - 1
}
